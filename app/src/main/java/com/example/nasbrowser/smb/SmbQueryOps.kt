package com.example.nasbrowser.smb

import com.hierynomus.msdtyp.AccessMask
import com.hierynomus.msfscc.FileAttributes
import com.hierynomus.msfscc.fileinformation.FileIdBothDirectoryInformation
import com.hierynomus.mssmb2.SMB2CreateDisposition
import com.hierynomus.mssmb2.SMB2CreateOptions
import com.hierynomus.mssmb2.SMB2ShareAccess
import com.hierynomus.smbj.share.DiskShare
import java.util.ArrayDeque
import java.util.EnumSet

/** Capacity of the share/volume behind a [DiskShare], in bytes. */
data class DiskSpace(val total: Long, val free: Long) {
    val used: Long get() = (total - free).coerceAtLeast(0)
    val percent: Int get() = if (total > 0) ((used * 100) / total).toInt().coerceIn(0, 100) else 0
}

data class CategoryStat(val label: String, val count: Int, val bytes: Long)

data class AnalysisResult(
    val fileCount: Int,
    val dirCount: Int,
    val totalBytes: Long,
    val truncated: Boolean,
    val categories: List<CategoryStat>,
    val largestFiles: List<SmbEntry>,
    val largestDirs: List<Pair<String, Long>>
)

/**
 * Read-only queries over one SMB2/3 [DiskShare]: recursive search, storage analysis, volume
 * capacity and partial file reads (used by the thumbnail loader).
 *
 * Every traversal is bounded: a huge movie library must never lock up the UI or the single SMB
 * session for minutes. All of this uses smbj only — no SMB1 fallback.
 */
object SmbQueryOps {

    /** Entries generated by this app's recycle bin; never shown or traversed. */
    const val TRASH_PREFIX = ".trash_"

    private fun smbPath(p: String): String = p.replace('/', '\\').trim('\\')

    private fun entries(ds: DiskShare, path: String): List<SmbEntry> {
        val cleaned = smbPath(path)
        val infos: List<FileIdBothDirectoryInformation> =
            if (cleaned.isEmpty()) ds.list("") else ds.list(cleaned)
        return infos
            .filter { it.fileName != "." && it.fileName != ".." && !it.fileName.startsWith(TRASH_PREFIX) }
            .map { info ->
                val isDir = (info.fileAttributes and 0x10L) != 0L
                val fullPath = if (path.isBlank()) info.fileName
                else "${path.trimEnd('/')}/${info.fileName}"
                SmbEntry(
                    name = info.fileName,
                    path = fullPath.replace('\\', '/'),
                    isDirectory = isDir,
                    size = info.endOfFile,
                    lastModified = info.changeTime?.toEpochMillis() ?: 0L
                )
            }
    }

    /** FS_FULL_SIZE_INFORMATION. Some servers reject it; in that case the UI just hides the bar. */
    fun diskSpace(ds: DiskShare): DiskSpace? = try {
        val s = ds.shareInformation
        if (s.totalSpace > 0L) DiskSpace(s.totalSpace, s.freeSpace) else null
    } catch (_: Exception) {
        null
    }

    /**
     * Breadth-first recursive search under [rootPath]. Returns [SmbEntry] objects whose `path` is
     * the FULL path inside the share, so tapping a hit can navigate/open it directly.
     */
    fun search(
        ds: DiskShare,
        rootPath: String,
        query: String,
        maxResults: Int = 400,
        maxDirs: Int = 1500
    ): List<SmbEntry> {
        val out = mutableListOf<SmbEntry>()
        val queue = ArrayDeque<String>()
        queue.add(rootPath.trimEnd('/'))
        var visitedDirs = 0
        while (queue.isNotEmpty() && visitedDirs < maxDirs && out.size < maxResults) {
            val dir = queue.removeFirst()
            visitedDirs++
            val children = try {
                entries(ds, dir)
            } catch (_: Exception) {
                continue   // an unreadable subfolder must not abort the whole search
            }
            for (e in children) {
                if (e.name.contains(query, ignoreCase = true)) {
                    out.add(e)
                    if (out.size >= maxResults) break
                }
                if (e.isDirectory) queue.add(e.path)
            }
        }
        return out
    }

    private data class Cat(var count: Int = 0, var bytes: Long = 0L)

    /** Recursively summarize the current directory: sizes, categories, largest files/folders. */
    fun analyze(ds: DiskShare, rootPath: String, maxItems: Int = 20000): AnalysisResult {
        val cats = LinkedHashMap<String, Cat>()
        val largest = mutableListOf<SmbEntry>()
        val dirSizes = mutableListOf<Pair<String, Long>>()
        var files = 0
        var dirs = 0
        var total = 0L
        var visited = 0
        var truncated = false

        val queue = ArrayDeque<String>()
        queue.add(rootPath.trimEnd('/'))
        while (queue.isNotEmpty() && visited < maxItems) {
            val dir = queue.removeFirst()
            var dirBytes = 0L
            val children = try {
                entries(ds, dir)
            } catch (_: Exception) {
                continue
            }
            for (e in children) {
                if (visited >= maxItems) { truncated = true; break }
                visited++
                if (e.isDirectory) {
                    dirs++
                    queue.add(e.path)
                } else {
                    files++
                    total += e.size
                    dirBytes += e.size
                    val c = cats.getOrPut(category(e.name)) { Cat() }
                    c.count++
                    c.bytes += e.size
                    if (e.size > 0L) largest.add(e)
                }
            }
            dirSizes.add(dir to dirBytes)
        }
        if (queue.isNotEmpty()) truncated = true

        return AnalysisResult(
            fileCount = files,
            dirCount = dirs,
            totalBytes = total,
            truncated = truncated,
            categories = cats.map { CategoryStat(it.key, it.value.count, it.value.bytes) }
                .sortedByDescending { it.bytes },
            largestFiles = largest.sortedByDescending { it.size }.take(10),
            largestDirs = dirSizes.sortedByDescending { it.second }.take(10)
        )
    }

    fun category(name: String): String {
        val ext = name.substringAfterLast('.', "").lowercase()
        return when (ext) {
            "jpg", "jpeg", "png", "gif", "webp", "bmp", "heic", "tif", "tiff", "svg", "raw" -> "图片"
            "mp4", "mkv", "mov", "avi", "wmv", "flv", "m4v", "ts", "webm", "rmvb" -> "视频"
            "mp3", "wav", "flac", "m4a", "aac", "ogg", "wma", "ape" -> "音频"
            "txt", "md", "log", "pdf", "doc", "docx", "xls", "xlsx", "ppt", "pptx",
            "epub", "mobi", "csv", "json", "xml", "srt", "ass" -> "文档"
            "zip", "rar", "7z", "tar", "gz", "bz2", "xz", "iso" -> "压缩包"
            "apk", "exe", "msi", "dmg", "jar", "deb", "rpm" -> "程序/安装包"
            else -> "其他"
        }
    }

    private val readMasks = EnumSet.of(AccessMask.GENERIC_READ)
    private val normalAttrs = EnumSet.of(FileAttributes.FILE_ATTRIBUTE_NORMAL)
    private val readShare = EnumSet.of(
        SMB2ShareAccess.FILE_SHARE_READ,
        SMB2ShareAccess.FILE_SHARE_WRITE,
        SMB2ShareAccess.FILE_SHARE_DELETE
    )
    private val fileOpts = EnumSet.of(SMB2CreateOptions.FILE_NON_DIRECTORY_FILE)

    /**
     * Read up to [maxBytes] from the start of a remote file (for thumbnails / text preview).
     *
     * A single SMB READ is capped by the negotiated MaxReadSize (typically 1 MB), so a photo
     * larger than that used to arrive truncated and Android decoded only its top strip. Loop
     * until EOF or the budget is exhausted so a JPEG/PNG is always complete.
     */
    fun readHead(ds: DiskShare, path: String, maxBytes: Int): ByteArray {
        if (maxBytes <= 0) return ByteArray(0)
        val f = ds.openFile(
            smbPath(path), readMasks, normalAttrs, readShare,
            SMB2CreateDisposition.FILE_OPEN, fileOpts
        )
        return try {
            val out = java.io.ByteArrayOutputStream()
            val buf = ByteArray(256 * 1024)
            var total = 0
            while (total < maxBytes) {
                val n = f.read(buf, total.toLong())
                if (n <= 0) break
                val take = minOf(n, maxBytes - total)
                out.write(buf, 0, take)
                total += take
            }
            out.toByteArray()
        } finally {
            try { f.close() } catch (_: Exception) {}
        }
    }

    /** Read a whole (small) remote text file as UTF-8. */
    fun readText(ds: DiskShare, path: String, maxBytes: Int = 2 * 1024 * 1024): String =
        String(readHead(ds, path, maxBytes), Charsets.UTF_8)
}
